/** 单日择日评估结果 */
export interface DayEvaluation {
  /** 公历日期 */
  date: string; // YYYY-MM-DD
  /** 日干支 */
  dayGanZhi: string;
  /** 建除十二神 */
  jianChu: JianChu;
  /** 黄道/黑道 */
  daoType: DaoType;
  /** 吉凶等级 */
  level: JianChuLevel;
  /** 评分（0-100，分数越高越吉利） */
  score: number;
  /** 宜（事项列表） */
  yi: string[];
  /** 忌（事项列表） */
  ji: string[];
  /** 备注说明 */
  desc: string;
}

/** 择日匹配结果 */
export interface ZhaiRiResult {
  /** 起始日期 */
  startDate: string;
  /** 结束日期 */
  endDate: string;
  /** 事项类型 */
  matter: MatterType;
  /** 推荐吉日（按分数倒序） */
  goodDays: DayEvaluation[];
  /** 总评估天数 */
  totalDays: number;
}
